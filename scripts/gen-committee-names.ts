/**
 * Rebuild lib/committee-names-data.js from the standing-orders and
 * speakers'-rulings corpus.
 *
 *   npm run gen:committee-names
 *
 * DATABASE_URL must point at the corpus database. The written module contains
 * the name tokens, citation label, and path. It does not contain section row ids.
 * tests/committee-names.test.ts calls this reader and skips unless
 * OPEN_ORDER_CORPUS_DB_HOST is set.
 */

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { Pool } from "pg";
import { committeeRecordsFromSections } from "../lib/committee-names";
import { verifiedDatabaseUrl } from "../lib/db-transport";

export const COMMITTEE_NAME_SQL = `
  select s.heading, s.path, s.citation_label
  from sections s
  join documents d on d.id = s.document_id
  where d.corpus in ('standing_orders', 'speakers_rulings')
    and (
      s.heading ilike '%committee%'
      or exists (select 1 from unnest(s.path) p where p ilike '%committee%')
    )
`;

export function publicCommitteeNameRecords(rows: Array<{
  sectionId?: string;
  id?: string;
  heading?: string | null;
  path?: string[] | null;
  citationLabel?: string;
  citation_label?: string;
}>): Array<{ tokens: string[]; citationLabel: string; path: string[] }> {
  return committeeRecordsFromSections(rows).map((record) => ({
    tokens: record.tokens,
    citationLabel: record.citationLabel,
    path: record.path,
  }));
}

export function renderCommitteeNamesModule(records: unknown): string {
  return `/** Generated by npm run gen:committee-names. Do not edit by hand. */\nexport const committeeNameRecords = ${JSON.stringify(records, null, 2)};\n`;
}

export async function readCommitteeNameRows(connectionString: string): Promise<Array<{
  heading: string | null;
  path: string[];
  citationLabel: string;
}>> {
  const pool = new Pool({
    connectionString: verifiedDatabaseUrl(connectionString, process.env.NODE_ENV || "development"),
  });
  try {
    const result = await pool.query(COMMITTEE_NAME_SQL);
    return result.rows.map((row: { heading: string | null; path: string[]; citation_label: string }) => ({
      heading: row.heading,
      path: row.path,
      citationLabel: row.citation_label,
    }));
  } finally {
    await pool.end();
  }
}

function committeeNamesModulePath(): string {
  return join(dirname(fileURLToPath(import.meta.url)), "../lib/committee-names-data.js");
}

async function main(): Promise<void> {
  const connectionString = process.env.DATABASE_URL;
  if (!connectionString) {
    console.error("DATABASE_URL is required.");
    process.exit(1);
  }
  const rows = await readCommitteeNameRows(connectionString);
  const records = publicCommitteeNameRecords(rows);
  writeFileSync(committeeNamesModulePath(), renderCommitteeNamesModule(records));
  console.log(`Wrote ${records.length} committee names.`);
}

const invoked = process.argv[1] ? pathToFileURL(process.argv[1]).href : "";
if (import.meta.url === invoked) {
  main().catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : "committee name generation failed");
    process.exit(1);
  });
}
