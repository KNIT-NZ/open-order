// app/api/search/route.ts
import { NextRequest, NextResponse } from "next/server";
import { randomUUID } from "node:crypto";
import { readPrivateSearchParams } from "@/lib/open-order/private-search-transport";
import { searchParamsSchema } from "@/lib/search";
import { searchProceduralAuthorities } from "@/lib/procedural-search";
import {
  buildSingularizedPhrase,
  cleanQuery,
  singularizeWord,
} from "@/lib/search-core";

function escapeHtml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

function buildPhraseVariants(query: string): string[] {
  const cleaned = cleanQuery(query);
  if (!cleaned) return [];

  const variants = new Set<string>();
  variants.add(cleaned);

  const singularized = buildSingularizedPhrase(cleaned);
  if (singularized) {
    variants.add(singularized);
  }

  return [...variants].filter(Boolean);
}

function highlightWholePhrase(text: string, query: string): string | null {
  const variants = buildPhraseVariants(query);
  if (variants.length === 0) return null;

  let html = escapeHtml(text);
  let matched = false;

  const sortedVariants = [...variants].sort((a, b) => b.length - a.length);

  for (const variant of sortedVariants) {
    const escapedVariant = variant.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const regex = new RegExp(`\\b${escapedVariant}\\b`, "gi");

    if (regex.test(text)) {
      matched = true;
      html = html.replace(regex, (match) => `<mark>${match}</mark>`);
    }
  }

  return matched ? html : null;
}

function highlightSingleWords(text: string, query: string): string {
  let html = escapeHtml(text);

  const words = cleanQuery(query)
    .split(/\s+/)
    .map((word) => singularizeWord(word))
    .filter(Boolean);

  for (const word of words) {
    const escapedWord = word.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const regex = new RegExp(`\\b${escapedWord}\\b`, "gi");
    html = html.replace(regex, (match) => `<mark>${match}</mark>`);
  }

  return html;
}

function buildTargetedHighlight(originalText: string, query: string): string {
  const isPhraseLike = cleanQuery(query).split(/\s+/).length >= 2;

  if (isPhraseLike) {
    const phraseHighlighted = highlightWholePhrase(originalText, query);
    if (phraseHighlighted) {
      return phraseHighlighted;
    }
  }

  return highlightSingleWords(originalText, query);
}

async function executeSearch(params: URLSearchParams) {
  const parsed = searchParamsSchema.safeParse({
    q: params.get("q") ?? "",
    corpus: params.get("corpus") ?? undefined,
    limit: params.get("limit") ?? "10",
    offset: params.get("offset") ?? "0",
  });

  if (!parsed.success) {
    return NextResponse.json(
      {
        ok: false,
        error: parsed.error.flatten(),
      },
      { status: 400 },
    );
  }

  const { q, corpus, limit, offset } = parsed.data;
  const started = Date.now();

  const response = await searchProceduralAuthorities({
    q,
    corpus: corpus ?? null,
    limit,
    offset,
    includeDebug: false,
  });

  const latencyMs = Date.now() - started;


  return NextResponse.json({
    ok: true,
    query: response.query,
    corpus: response.corpus,
    limit: response.limit,
    offset: response.offset,
    total: response.total,
    hasMore: response.hasMore,
    latencyMs,
    results: response.results.map((row) => ({
      sectionId: row.sectionId,
      sectionKey: row.sectionKey,
      citationLabel: row.citationLabel,
      heading: row.heading,
      headingHighlighted: row.heading
        ? buildTargetedHighlight(row.heading, response.query)
        : null,
      sectionContentHighlighted: buildTargetedHighlight(
        row.sectionContent,
        response.query,
      ),
      path: row.path,
      documentSlug: row.documentSlug,
      documentTitle: row.documentTitle,
      documentCorpus: row.documentCorpus,
      sourceUrl: row.sourceUrl,
      sourceAnchor: row.sourceAnchor,
      rank: row.rank,
      sectionRank: row.sectionRank,
      pathRank: row.pathRank,
      bodyRank: row.bodyRank,
      chunkRank: row.chunkRank,
      clusterSupportCount: row.clusterSupportCount,
      sectionContent: row.sectionContent,
      matchSignals: row.matchSignals,
    })),
  });
}

// Do not make a user query or derived diagnostics a persistence event.
// The request reference is generated by this server; it is not a user identifier.
function privateSearchResponse(response: NextResponse, requestId: string): NextResponse {
  response.headers.set("Cache-Control", "private, no-store, no-transform");
  response.headers.set("Referrer-Policy", "no-referrer");
  response.headers.set("X-Open-Order-Request-Id", requestId);
  return response;
}

export async function POST(request: NextRequest) {
  const requestId = randomUUID();
  try {
    // Reject URL query parameters without inspecting or echoing their contents.
    if (request.nextUrl.search) {
      return privateSearchResponse(NextResponse.json({ error: "Use the JSON request body." }, { status: 400 }), requestId);
    }
    const params = await readPrivateSearchParams(request);
    if (!params) {
      return privateSearchResponse(NextResponse.json({ error: "Invalid search request." }, { status: 400 }), requestId);
    }
    return privateSearchResponse(await executeSearch(params), requestId);
  } catch {
    return privateSearchResponse(NextResponse.json({ error: "Search is temporarily unavailable." }, { status: 500 }), requestId);
  }
}

export function GET() {
  const response = NextResponse.json({ error: "Search now requires POST with a JSON body." }, { status: 405 });
  response.headers.set("Allow", "POST");
  return privateSearchResponse(response, randomUUID());
}
